/**
 * Writes `src/lib/og/stickerShapes.ts`, the stickers the session cards are
 * scattered with, from the vector artwork the repository already carries:
 *
 * - BOLD: groups of paths from `src/assets/brand/stickers.svg`, the DF25
 *   sticker sheet. Each group is one sticker; its bounds are measured by
 *   rendering it and trimming the empty space around it.
 * - THIN: the outline stickers of the Kansai key visual
 *   (`src/routes/kansai/_components/heroShapes.ts`, `kv/Glyph.astro`), plus a
 *   few drawn here to the same keyline.
 *
 * To add a sticker: add its path numbers to `BOLD` (1-based, in the order the
 * sheet's `<path>`s appear), or a shape to `DRAWN`; then
 *
 *     pnpm og:stickers
 *
 * The cards pick stickers by a seed from the session id, so adding or
 * removing one changes which stickers existing cards show.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";
import { HERO_SHAPES } from "../src/routes/kansai/_components/heroShapes";
import type { Shape } from "../src/lib/og/stickerShapes";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(repo, "src/lib/og/stickerShapes.ts");

/**
 * The sheet's paths that make up each bold sticker. Left out: the long ones
 * (ellipsis, quotes, minus, three dots), which only ever fit a strip and would
 * sit tiny in the square spaces a card has.
 */
const BOLD: Record<string, number[]> = {
  brackets: [4, 5],
  arrow: [7],
  dot: [21],
  slashes: [8, 9],
  semicolon: [31, 32],
  braces: [10, 11],
  arc: [24],
  chevrons: [22, 23],
  cee: [25],
  equals: [12, 13],
  plusRed: [30],
  hash: [28, 29],
  colon: [19, 20],
  cross: [26, 27],
  plusBlue: [33],
};

