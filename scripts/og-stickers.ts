/** A drawing's bounds on the sheet: rendered, then trimmed to its ink. */
async function bounds(markup: string) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 2600 1500" width="2600" height="1500">${markup}</svg>`;
  const { info } = await sharp(Buffer.from(svg))
    .trim()
    .toBuffer({ resolveWithObject: true });
  return {
    x: -(info.trimOffsetLeft ?? 0),
    y: -(info.trimOffsetTop ?? 0),
    width: info.width,
    height: info.height,
  };
}

const sheet = readFileSync(join(repo, "src/assets/brand/stickers.svg"), "utf8");
const paths = sheet.match(/<path[^>]*\/>/g) ?? [];

const bold: Shape[] = [];
for (const [name, indices] of Object.entries(BOLD)) {
  const body = indices
    .map((i) => {
      const path = paths[i - 1];
      if (!path) throw new Error(`${name}: the sheet has no path ${i}`);
      return path.replace(/ id="[^"]*"/, "");
    })
    .join("");
  const { x, y, width, height } = await bounds(body);
  const pad = 4;
  bold.push({
    name,
    viewBox: `${x - pad} ${y - pad} ${width + 2 * pad} ${height + 2 * pad}`,
    body,
  });
}

const thin: Shape[] = [
  ...HERO_SHAPES.map(({ name, viewBox, body }) => ({
    name,
    viewBox,
    body: body.replace(/>\s+</g, "><"),
  })),
  ...DRAWN,
];

writeFileSync(
  OUT,
  `/**
 * The sticker artwork, as vectors. Generated by \`scripts/og-stickers.ts\`
 * (\`pnpm og:stickers\`) — edit that, not this:
 *
 * - BOLD: groups of paths from \`src/assets/brand/stickers.svg\` — the DF25
 *   sticker sheet's bold glyphs — each with the bounds it is cut out by. The
 *   paths keep the sheet's own fills, keyline and transforms.
 * - THIN: the monoline glyphs — the outline stickers the Kansai key visual
 *   carries (\`src/routes/kansai/_components/heroShapes.ts\`, \`kv/Glyph.astro\`),
 *   plus square brackets, equals, semicolon and colon drawn to the same
 *   keyline. Unstyled: whoever draws them sets the stroke.
 */

export interface Shape {
  name: string;
  viewBox: string;
  body: string;
}

export const BOLD: readonly Shape[] = ${JSON.stringify(bold, null, 2)};

export const THIN: readonly Shape[] = ${JSON.stringify(thin, null, 2)};
`,
);
console.log(`${OUT}: ${bold.length} bold, ${thin.length} thin`);
